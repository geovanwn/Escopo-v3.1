import { z } from 'zod';

export const payrollInputSchema = z.object({
    he50_qtde: z.coerce.number().min(0, 'Quantidade de H.E. 50% não pode ser negativa').default(0),
    he100_qtde: z.coerce.number().min(0, 'Quantidade de H.E. 100% não pode ser negativa').default(0),
    faltas_dias: z.coerce.number().min(0, 'Dias de faltas não pode ser negativo').max(31, 'Máximo de 31 dias').default(0),
    atrasos_mins: z.coerce.number().min(0, 'Minutos de atraso não pode ser negativo').default(0),
    comissao_valor: z.coerce.number().min(0, 'Valor da comissão não pode ser negativo').default(0),
    bonus_valor: z.coerce.number().min(0, 'Valor do bônus não pode ser negativo').default(0),
    adicional_periculosidade: z.boolean().default(false),
    adicional_insalubridade: z.enum(['nenhum', 'min', 'med', 'max']).default('nenhum'),
    desc_vt: z.boolean().default(false),
    transportVoucherValue: z.coerce.number().optional(),
    desc_plano_saude: z.coerce.number().min(0).default(0),
    desc_adiantamento: z.coerce.number().min(0).default(0),
    desc_outros: z.coerce.number().min(0).default(0),
    proLaboreOverride: z.coerce.number().optional(),
    diasUteis: z.coerce.number().min(1).max(31).default(25),
    diasDescanso: z.coerce.number().min(0).max(31).default(5),
    media_variaveis_valor: z.coerce.number().min(0).default(0),
    customEvents: z.array(z.any()).optional(),
    calculationType: z.enum(['folha_mensal', 'decimo_terceiro', 'ferias', 'rescisao']).default('folha_mensal'),
    rescisaoReason: z.string().optional(),
    rescisaoNotice: z.enum(['indenizado', 'trabalhado', 'nao_cumprido']).optional(),
    rescisaoVacationBalance: z.coerce.number().optional(),
    decimoTerceiroParcela: z.enum(['1', '2', 'unica']).optional(),
    feriasDias: z.coerce.number().min(1).max(30).optional(),
    feriasAbono: z.boolean().optional(),
    rescisaoDate: z.string().optional(),
    rescisaoAfastamentoCode: z.string().optional(),
    vacationStart: z.string().optional(),
    selectedRubrics: z.array(z.string()).optional(),
    month: z.string().optional(),
    year: z.string().optional(),
    workedDays: z.coerce.number().min(0).max(31).optional(),
    isZeroed: z.boolean().default(false).optional(),
});

export type PayrollInputValues = z.infer<typeof payrollInputSchema>;
